// 演示时间线锚点：整份 mock 数据的事件都发生在 2026-07-18 ~ 2026-07-26 这段「剧本时间」里。
// 把这些时间戳整体平移到「现在」，有两个好处：
//   1) 截图与在线 demo 永远看起来是新鲜的，不会显示成几个月前的旧数据；
//   2) 仪表盘的 7 天 / 30 天窗口（按真实今天做 cutoff）不会因为写死日期而变空。
// 相对间隔完全保持不变，因此任务的运行时长、会话先后顺序都不受影响。
const NARRATIVE_NEWEST = Date.parse("2026-07-26T03:58:22Z");
const TIME_SHIFT_MS = Date.now() - NARRATIVE_NEWEST;

// 导出给 handler.ts 复用：handler 里的运行态时间戳必须和这里走同一套平移，
// 否则「今天刚发生的复核」会显示成剧本里的旧日期。
export const T = (iso: string) => new Date(Date.parse(iso) + TIME_SHIFT_MS).toISOString();
// unix 秒版本：给 created_unix / last_activity_unix 这类字段用，和 T() 走同一套平移。
export const unixT = (iso: string) => Math.floor((Date.parse(iso) + TIME_SHIFT_MS) / 1000);

